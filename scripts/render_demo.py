"""Render real agent runs (question -> tool calls -> verified answer) to docs/demo.html.

    python scripts/render_demo.py
"""
from __future__ import annotations

import sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from finagent import AnalystAgent  # noqa: E402

QUESTIONS = [
    "What is Northwind Robotics' FY2025 return on assets? Return on assets is FY2025 net income divided by the average "
    "total assets between FY2024 and FY2025. Round to two decimal places, as a percentage.",
    "What was the year-over-year growth rate of Northwind Robotics' net sales from FY2024 to FY2025? Round to two decimal places.",
    "Which of Northwind Robotics' segments grew the fastest in FY2025?",
    "How much of Northwind Robotics' long-term debt principal is scheduled to be repaid in 2028?",
]


def card(ans) -> str:
    steps = "".join(
        f'<li><code class="tool">{escape(s.tool)}</code> <code>{escape(", ".join(f"{k}={v!r}" for k, v in s.args.items()))}</code>'
        f'<pre>{escape(s.output.splitlines()[0][:150] if s.output else "")}</pre></li>' for s in ans.steps)
    badge = '<span class="ok">✓ verified against the filing</span>' if ans.grounded else '<span class="warn">⚠ unverified</span>'
    srcs = " ".join(f'<span class="pg">{c.label}</span>' for c in ans.citations)
    return f"""<section class="card"><div class="q">{escape(ans.question)}</div>
<ol class="trace">{steps}</ol>
<div class="a">{escape(ans.answer)}</div><div class="meta">{badge} · Sources {srcs} · {len(ans.steps)} tool calls</div></section>"""


def main():
    agent = AnalystAgent.from_file(ROOT / "samples" / "NORTHWIND_2025_10K.pdf")
    cards = "".join(card(agent.ask(q)) for q in QUESTIONS)
    html = f"""<!DOCTYPE html><html lang="en"><head><meta charset="utf-8"><title>10-K Analyst Agent demo</title>
<style>
body{{margin:0;background:#0f1419;color:#e6e9ef;font:15px/1.5 system-ui,-apple-system,Segoe UI,Roboto,sans-serif}}
main{{max-width:1000px;margin:0 auto;padding:30px 24px}}
h1{{font-size:26px;margin:0}} .sub{{color:#8b95a7;margin:4px 0 22px}}
.card{{background:#171d25;border:1px solid #263040;border-radius:14px;padding:16px 20px;margin-bottom:14px}}
.q{{font-weight:600;color:#fff}} .trace{{margin:10px 0;padding-left:20px;color:#9aa4b5;font-size:13px}}
.trace li{{margin:4px 0}} pre{{margin:2px 0 0;white-space:pre-wrap;color:#6f7b8f;font-size:12px}}
code{{font-size:12.5px;color:#c7d0dd}} code.tool{{color:#7cc4ff;font-weight:600}}
.a{{background:#0f2a1d;border:1px solid #1f5a3c;border-radius:10px;padding:10px 14px;font-weight:600;color:#c9f7da}}
.meta{{color:#8b95a7;font-size:13px;margin-top:8px}} .ok{{color:#4ade80}} .warn{{color:#fbbf24}}
.pg{{background:#263040;border-radius:6px;padding:1px 7px;color:#cfd8e6}}
</style></head><body><main>
<h1>📊 10-K Analyst Agent</h1>
<div class="sub">{escape(agent.tools.overview())}<br>Real runs: every number comes from a tool call, every calculation from the calculator, every answer cites its page.</div>
{cards}
<div class="sub">Fictional sample company. Generated by scripts/render_demo.py.</div>
</main></body></html>"""
    out = ROOT / "docs" / "demo.html"
    out.write_text(html, encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
